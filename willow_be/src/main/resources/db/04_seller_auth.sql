-- ============================================================================
-- Willow - seller dashboard sign-in
-- Database: willow_local (PostgreSQL)
--
-- Tables: sellers, seller_sessions
-- Run after 02_dashboard.sql. The store itself stays in store_profile; signing
-- up as the seller fills in its name and owner details.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- sellers: who may sign in to the seller dashboard. Willow is a single store,
-- so the first sign-up creates the owner account and no further sign-ups are
-- accepted (the application enforces this).
-- ---------------------------------------------------------------------------
CREATE TABLE sellers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_sellers_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- seller_sessions: one row per signed-in browser. The browser holds a random
-- token; only its SHA-256 hash is stored here. Logging out deletes the row.
-- ---------------------------------------------------------------------------
CREATE TABLE seller_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id  BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT uq_seller_sessions_token  UNIQUE (token_hash),
    CONSTRAINT fk_seller_sessions_seller FOREIGN KEY (seller_id) REFERENCES sellers (id) ON DELETE CASCADE
);

CREATE INDEX idx_seller_sessions_seller ON seller_sessions (seller_id);

COMMIT;
