-- ============================================================================
-- Willow - seller dashboard schema (willow_dashboard)
-- Database: willow_local (PostgreSQL)
--
-- Tables: store_profile, seller_settings, stock_movements, recommendations
-- Run after 01_storefront.sql. The dashboard also reads and writes the
-- storefront's products, orders and order_items tables.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- store_profile: the seller's public identity (Store Profile page).
-- Always exactly one row, id = 1.
-- ---------------------------------------------------------------------------
CREATE TABLE store_profile (
    id            BIGINT       PRIMARY KEY DEFAULT 1,
    store_name    VARCHAR(120) NOT NULL,
    tagline       VARCHAR(160),
    description   VARCHAR(1000),
    owner_name    VARCHAR(120),
    contact_email VARCHAR(255),
    contact_phone VARCHAR(20),
    address_line  VARCHAR(300),
    city          VARCHAR(80),
    state         VARCHAR(80),
    pincode       VARCHAR(10),
    gstin         VARCHAR(15),
    logo_url      VARCHAR(500),
    website       VARCHAR(255),
    instagram     VARCHAR(60),
    updated_at    TIMESTAMPTZ,

    CONSTRAINT ck_store_profile_single CHECK (id = 1)
);

-- ---------------------------------------------------------------------------
-- seller_settings: how the store operates (Settings page).
-- Always exactly one row, id = 1.
-- ---------------------------------------------------------------------------
CREATE TABLE seller_settings (
    id                      BIGINT         PRIMARY KEY DEFAULT 1,
    low_stock_threshold     INTEGER        NOT NULL DEFAULT 10,    -- at or below this, a product is "low stock"
    auto_confirm_orders     BOOLEAN        NOT NULL DEFAULT FALSE, -- new orders skip PENDING
    order_notifications     BOOLEAN        NOT NULL DEFAULT TRUE,
    low_stock_alerts        BOOLEAN        NOT NULL DEFAULT TRUE,
    return_window_days      INTEGER        NOT NULL DEFAULT 7,
    shipping_fee            NUMERIC(12, 2) NOT NULL DEFAULT 99,
    free_shipping_threshold NUMERIC(12, 2) NOT NULL DEFAULT 1999,  -- subtotals at or above this ship free
    simulate_live_orders    BOOLEAN        NOT NULL DEFAULT FALSE, -- developer tool: generates test orders
    updated_at              TIMESTAMPTZ,

    CONSTRAINT ck_seller_settings_single CHECK (id = 1),
    CONSTRAINT ck_seller_settings_values CHECK (
        low_stock_threshold >= 0 AND return_window_days >= 0
        AND shipping_fee >= 0 AND free_shipping_threshold >= 0
    )
);

-- ---------------------------------------------------------------------------
-- stock_movements: append-only log of every stock change (Inventory page)
-- ---------------------------------------------------------------------------
CREATE TABLE stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT      NOT NULL,
    quantity_change INTEGER     NOT NULL,                    -- positive adds stock, negative removes it
    balance_after   INTEGER     NOT NULL,                    -- stock level right after this change
    reason          VARCHAR(20) NOT NULL,
    note            VARCHAR(300),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT ck_stock_movements_reason  CHECK (reason IN ('INITIAL', 'RESTOCK', 'SALE', 'CANCELLATION', 'RETURN', 'ADJUSTMENT', 'DAMAGED')),
    CONSTRAINT ck_stock_movements_balance CHECK (balance_after >= 0)
);

CREATE INDEX idx_stock_mv_created ON stock_movements (created_at);
CREATE INDEX idx_stock_mv_product ON stock_movements (product_id);

-- ---------------------------------------------------------------------------
-- recommendations: seller-approved outfit pairs (Curated Picks page).
-- The storefront only ever suggests pairs that exist here.
-- ---------------------------------------------------------------------------
CREATE TABLE recommendations (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    top_id   BIGINT NOT NULL,
    pants_id BIGINT NOT NULL,

    CONSTRAINT fk_recommendations_top   FOREIGN KEY (top_id)   REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_recommendations_pants FOREIGN KEY (pants_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT uq_recommendations_pair  UNIQUE (top_id, pants_id),
    CONSTRAINT ck_recommendations_pair  CHECK (top_id <> pants_id)
);

CREATE INDEX idx_recommendations_pants ON recommendations (pants_id);

COMMIT;
