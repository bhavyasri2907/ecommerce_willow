-- ============================================================================
-- Willow - real checkout (Cash on Delivery)
-- Database: willow_local (PostgreSQL)
--
-- Changes: orders (full delivery address, payment status, checkout reference),
--          order number sequence
-- Tables:  order_status_history
-- Run after 07_curated_fit.sql.
--
-- Checkout now requires a signed-in shopper and a saved address (addresses
-- table from 01_storefront.sql). Orders are linked to the customer through
-- orders.customer_id so they show up under My Orders.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- orders: the rest of the delivery address, copied from the shopper's saved
-- address at checkout so later edits to the address book never change history.
-- ---------------------------------------------------------------------------
ALTER TABLE orders ADD COLUMN shipping_state   VARCHAR(80);
ALTER TABLE orders ADD COLUMN shipping_pincode VARCHAR(10);

-- ---------------------------------------------------------------------------
-- orders: payment state, separate from fulfilment state.
--   PENDING  - not collected yet (COD before delivery)
--   PAID     - collected (COD on delivery, or prepaid in future)
--   REFUNDED - money handed back after a return
--   VOID     - order cancelled before any money changed hands
-- ---------------------------------------------------------------------------
ALTER TABLE orders ADD COLUMN payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING';
ALTER TABLE orders ADD CONSTRAINT ck_orders_payment_status
    CHECK (payment_status IN ('PENDING', 'PAID', 'REFUNDED', 'VOID'));

-- ---------------------------------------------------------------------------
-- orders: the browser's checkout id. Placing the same checkout twice (double
-- click, network retry) returns the orders already created instead of new ones.
-- One checkout makes one order per store, hence store_id in the key.
-- ---------------------------------------------------------------------------
ALTER TABLE orders ADD COLUMN checkout_ref VARCHAR(64);
CREATE UNIQUE INDEX uq_orders_checkout ON orders (customer_id, checkout_ref, store_id)
    WHERE checkout_ref IS NOT NULL;

-- My Orders lists a customer's orders newest first.
DROP INDEX IF EXISTS idx_orders_customer;
CREATE INDEX idx_orders_customer ON orders (customer_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Order numbers come from a database sequence so several API instances can
-- run side by side without handing out the same number.
-- ---------------------------------------------------------------------------
CREATE SEQUENCE order_number_seq START WITH 100001 INCREMENT BY 1;
SELECT setval('order_number_seq',
              GREATEST(100000, COALESCE((SELECT max(substring(order_number FROM 4)::BIGINT) FROM orders), 100000)),
              true);

-- ---------------------------------------------------------------------------
-- order_status_history: every status an order has been in, who moved it there
-- and why. Drives the tracking timeline for shoppers and sellers.
-- ---------------------------------------------------------------------------
CREATE TABLE order_status_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    actor      VARCHAR(20)  NOT NULL,                       -- CUSTOMER, SELLER or SYSTEM
    note       VARCHAR(300),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_order_status_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_status_history_status CHECK (status IN ('PENDING', 'CONFIRMED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'RETURNED')),
    CONSTRAINT ck_order_status_history_actor  CHECK (actor IN ('CUSTOMER', 'SELLER', 'SYSTEM'))
);

CREATE INDEX idx_order_status_history_order ON order_status_history (order_id, created_at);

-- Orders placed before this script get their current status as their only history entry.
INSERT INTO order_status_history (order_id, status, actor, created_at)
SELECT id, status, 'SYSTEM', created_at FROM orders;

COMMIT;
