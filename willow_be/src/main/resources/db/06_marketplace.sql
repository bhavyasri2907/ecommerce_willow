-- ============================================================================
-- Willow - marketplace: many sellers, each with their own store
-- Database: willow_local (PostgreSQL)
--
-- Changes: store_profile becomes stores (one row per store); seller_settings,
--          sellers, products and orders each belong to a store.
-- Run after 05_product_catalog.sql.
--
-- Anything that existed before this script belongs to the original store.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- stores: one row per seller's store (was the single-row store_profile).
-- ---------------------------------------------------------------------------
ALTER TABLE store_profile RENAME TO stores;
ALTER INDEX store_profile_pkey RENAME TO pk_stores;
ALTER TABLE stores DROP CONSTRAINT ck_store_profile_single;
ALTER TABLE stores ALTER COLUMN id DROP DEFAULT;
ALTER TABLE stores ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('stores', 'id'), COALESCE((SELECT max(id) FROM stores), 0) + 1, false);
ALTER TABLE stores ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Shoppers tell stores apart by name, so two stores cannot share one.
CREATE UNIQUE INDEX uq_stores_name ON stores (lower(store_name));

-- ---------------------------------------------------------------------------
-- seller_settings: how one store operates. One row per store.
-- ---------------------------------------------------------------------------
DELETE FROM seller_settings WHERE id NOT IN (SELECT id FROM stores);
ALTER TABLE seller_settings DROP CONSTRAINT ck_seller_settings_single;
ALTER TABLE seller_settings RENAME COLUMN id TO store_id;
ALTER TABLE seller_settings ALTER COLUMN store_id DROP DEFAULT;
ALTER TABLE seller_settings
    ADD CONSTRAINT fk_seller_settings_store FOREIGN KEY (store_id) REFERENCES stores (id) ON DELETE CASCADE;

-- ---------------------------------------------------------------------------
-- sellers: each seller signs in to their own store.
-- ---------------------------------------------------------------------------
ALTER TABLE sellers ADD COLUMN store_id BIGINT;
UPDATE sellers SET store_id = (SELECT min(id) FROM stores);
ALTER TABLE sellers ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE sellers ADD CONSTRAINT fk_sellers_store FOREIGN KEY (store_id) REFERENCES stores (id) ON DELETE CASCADE;
CREATE INDEX idx_sellers_store ON sellers (store_id);

-- ---------------------------------------------------------------------------
-- products: every product is listed by one store. SKUs only need to be unique
-- within a store, not across the whole marketplace.
-- ---------------------------------------------------------------------------
ALTER TABLE products ADD COLUMN store_id BIGINT;
UPDATE products SET store_id = (SELECT min(id) FROM stores);
ALTER TABLE products ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE products ADD CONSTRAINT fk_products_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_products_store ON products (store_id);

ALTER TABLE products DROP CONSTRAINT uq_products_sku;
ALTER TABLE products ADD CONSTRAINT uq_products_store_sku UNIQUE (store_id, sku);

-- ---------------------------------------------------------------------------
-- orders: an order is fulfilled by one store. A bag with items from several
-- stores is split into one order per store at checkout.
-- ---------------------------------------------------------------------------
ALTER TABLE orders ADD COLUMN store_id BIGINT;
UPDATE orders SET store_id = (SELECT min(id) FROM stores);
ALTER TABLE orders ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE orders ADD CONSTRAINT fk_orders_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_orders_store ON orders (store_id);

COMMIT;
