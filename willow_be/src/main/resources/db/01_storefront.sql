-- ============================================================================
-- Willow - storefront schema (willow_fe)
-- Database: willow_local (PostgreSQL)
--
-- Tables: customers, addresses, products, cart_items, wishlist_items,
--         orders, order_items, reviews
-- Run this file first, then 02_dashboard.sql.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- customers: a shopper's account (My Account)
-- ---------------------------------------------------------------------------
CREATE TABLE customers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_customers_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- addresses: a customer's saved delivery addresses (My Account > Addresses)
-- ---------------------------------------------------------------------------
CREATE TABLE addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT       NOT NULL,
    full_name    VARCHAR(120) NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    address_line VARCHAR(300) NOT NULL,
    city         VARCHAR(80)  NOT NULL,
    state        VARCHAR(80)  NOT NULL,
    pincode      VARCHAR(10)  NOT NULL,
    is_default   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_addresses_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE
);

CREATE INDEX idx_addresses_customer ON addresses (customer_id);
-- A customer can have only one default address.
CREATE UNIQUE INDEX uq_addresses_default ON addresses (customer_id) WHERE is_default;

-- ---------------------------------------------------------------------------
-- products: the catalogue. Shoppers see rows with status = 'LIVE'.
-- ---------------------------------------------------------------------------
CREATE SEQUENCE product_seq START WITH 1000 INCREMENT BY 1;

CREATE TABLE products (
    id             BIGINT         PRIMARY KEY DEFAULT nextval('product_seq'),
    name           VARCHAR(120)   NOT NULL,
    sku            VARCHAR(40),
    type           VARCHAR(20)    NOT NULL,                  -- category
    status         VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    color          VARCHAR(60),
    hex            VARCHAR(7),                               -- swatch colour, e.g. #8C2D42
    style          VARCHAR(40),
    price          NUMERIC(12, 2) NOT NULL,
    original_price NUMERIC(12, 2),                           -- "compare at" price; set when on sale
    stock          INTEGER        NOT NULL DEFAULT 0,
    sizes          VARCHAR(200),                             -- comma separated, e.g. XS,S,M,L
    image_url      VARCHAR(500),
    description    VARCHAR(1000),
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uq_products_sku     UNIQUE (sku),
    CONSTRAINT ck_products_type    CHECK (type IN ('TOP', 'PANTS', 'SHOES', 'BAG', 'ACCESSORY')),
    CONSTRAINT ck_products_status  CHECK (status IN ('LIVE', 'DRAFT', 'ARCHIVED')),
    CONSTRAINT ck_products_price   CHECK (price > 0),
    CONSTRAINT ck_products_compare CHECK (original_price IS NULL OR original_price > 0),
    CONSTRAINT ck_products_stock   CHECK (stock >= 0)
);

ALTER SEQUENCE product_seq OWNED BY products.id;

CREATE INDEX idx_products_type   ON products (type);
CREATE INDEX idx_products_status ON products (status);

-- ---------------------------------------------------------------------------
-- cart_items: what a customer has in their bag
-- ---------------------------------------------------------------------------
CREATE TABLE cart_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL,
    product_id  BIGINT      NOT NULL,
    size        VARCHAR(20),
    quantity    INTEGER     NOT NULL DEFAULT 1,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_cart_items_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product  FOREIGN KEY (product_id)  REFERENCES products (id)  ON DELETE CASCADE,
    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);

-- The same product + size appears once per cart; adding it again raises the quantity.
CREATE UNIQUE INDEX uq_cart_items_line ON cart_items (customer_id, product_id, COALESCE(size, ''));

-- ---------------------------------------------------------------------------
-- wishlist_items: products a customer has saved (My Wishlist)
-- ---------------------------------------------------------------------------
CREATE TABLE wishlist_items (
    customer_id BIGINT      NOT NULL,
    product_id  BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_wishlist_items          PRIMARY KEY (customer_id, product_id),
    CONSTRAINT fk_wishlist_items_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_items_product  FOREIGN KEY (product_id)  REFERENCES products (id)  ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- orders: one row per checkout. Contact and shipping details are copied onto
-- the order so later edits to the account or address never change history.
-- ---------------------------------------------------------------------------
CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(20)    NOT NULL,
    customer_id      BIGINT,                                 -- NULL for guest checkout
    customer_name    VARCHAR(120)   NOT NULL,
    customer_email   VARCHAR(255)   NOT NULL,
    customer_phone   VARCHAR(20),
    shipping_address VARCHAR(300),
    shipping_city    VARCHAR(80),
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    payment_method   VARCHAR(20)    NOT NULL,
    subtotal         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    shipping_fee     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total            NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_customer     FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_status       CHECK (status IN ('PENDING', 'CONFIRMED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'RETURNED')),
    CONSTRAINT ck_orders_payment      CHECK (payment_method IN ('UPI', 'CARD', 'NET_BANKING', 'COD')),
    CONSTRAINT ck_orders_amounts      CHECK (subtotal >= 0 AND shipping_fee >= 0 AND total >= 0)
);

CREATE INDEX idx_orders_status     ON orders (status);
CREATE INDEX idx_orders_created_at ON orders (created_at);
CREATE INDEX idx_orders_customer   ON orders (customer_id);

-- ---------------------------------------------------------------------------
-- order_items: the lines on an order. Name and unit price are copied at
-- checkout so catalogue edits never rewrite what the customer paid.
-- ---------------------------------------------------------------------------
CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL,
    product_id   BIGINT         NOT NULL,
    product_name VARCHAR(120)   NOT NULL,
    size         VARCHAR(20),
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL,

    CONSTRAINT fk_order_items_order    FOREIGN KEY (order_id)   REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product  FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price    CHECK (unit_price >= 0)
);

CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);

-- ---------------------------------------------------------------------------
-- reviews: one rating per customer per product (My Account > My Reviews)
-- ---------------------------------------------------------------------------
CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT      NOT NULL,
    customer_id BIGINT      NOT NULL,
    rating      SMALLINT    NOT NULL,
    comment     VARCHAR(1000),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_reviews_product  FOREIGN KEY (product_id)  REFERENCES products (id)  ON DELETE CASCADE,
    CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT uq_reviews_once     UNIQUE (product_id, customer_id),
    CONSTRAINT ck_reviews_rating   CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_reviews_customer ON reviews (customer_id);

COMMIT;
