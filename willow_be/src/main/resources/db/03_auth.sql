-- ============================================================================
-- Willow - storefront sign-in sessions
-- Database: willow_local (PostgreSQL)
--
-- Tables: customer_sessions
-- Run after 01_storefront.sql. Accounts themselves live in the customers table.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- customer_sessions: one row per signed-in browser. The browser holds a random
-- token; only its SHA-256 hash is stored here. Logging out deletes the row.
-- ---------------------------------------------------------------------------
CREATE TABLE customer_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL,

    CONSTRAINT uq_customer_sessions_token    UNIQUE (token_hash),
    CONSTRAINT fk_customer_sessions_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE
);

CREATE INDEX idx_customer_sessions_customer ON customer_sessions (customer_id);

COMMIT;
